struct thread_info
{
    uint32_t zeroBasedIndex;
    bool isRunning;
    struct ltrx_trigger eventTrigger;
    const struct ltrx_network_protocol *protocol;
    struct ltrx_network_protocol_handle *handle;
    enum ltrx_network_return netSendState;
};

